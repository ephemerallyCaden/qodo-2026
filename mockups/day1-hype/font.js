function glyphFor(font, ch) {
  const g = font.glyphs[ch] ?? font.glyphs[ch.toUpperCase()];
  if (!g) throw new Error(`missing glyph ${JSON.stringify(ch)}`);
  return g;
}

/** Rasterise text into a mask: { w, h, on(x, y) }. */
export function rasterText(str, font) {
  const glyphs = [...str].map((ch) => glyphFor(font, ch));
  const w = glyphs.reduce((sum, g) => sum + g[0].length + font.spacing, -font.spacing);
  const h = font.height;
  const bits = new Uint8Array(Math.max(w, 0) * h);
  let cx = 0;
  for (const g of glyphs) {
    g.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') bits[y * w + cx + x] = 1;
    });
    cx += g[0].length + font.spacing;
  }
  return { w, h, on: (x, y) => x >= 0 && y >= 0 && x < w && y < h && bits[y * w + x] === 1 };
}

export const textWidth = (str, font) => rasterText(str, font).w;

/**
 * Draw pixel text. Options: color, color2 + splitRow (two-tone fill),
 * outline (8-neighbour outline colour), shadow (1px drop shadow under the
 * outlined shape). Returns the text width.
 */
export function drawText(ctx, str, x, y, font, { color, color2, splitRow = 99, outline, shadow } = {}) {
  const m = rasterText(str, font);
  x = Math.round(x);
  y = Math.round(y);
  const dilated = (i, j) => {
    if (!outline) return m.on(i, j);
    for (let dj = -1; dj <= 1; dj++) for (let di = -1; di <= 1; di++) if (m.on(i + di, j + dj)) return true;
    return false;
  };
  const px = (c, ax, ay) => {
    ctx.fillStyle = c;
    ctx.fillRect(x + ax, y + ay, 1, 1);
  };
  for (let j = -1; j <= m.h + 1; j++) {
    for (let i = -1; i <= m.w; i++) {
      const d = dilated(i, j);
      if (shadow && !d && dilated(i, j - 1)) px(shadow, i, j);
      if (d && !m.on(i, j)) px(outline, i, j);
      if (m.on(i, j)) px(j >= splitRow ? color2 : color, i, j);
    }
  }
  return m.w;
}
