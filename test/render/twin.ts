// Text twin of a golden image (#31 AC 6): pixel counts per palette entry, so a reviewer who can't see
// images (Qodo) can still review a render change. Each colour's bounding box shows where it moved,
// the RGBA hash shows that something changed even when every count stayed the same, and the env
// line records where the golden was made (goldens are authoritative only there).
import { createHash } from 'node:crypto';
import { byCodepoint } from '../../src/core/canonical-json.js';
import type { RenderStats } from '../../src/core/contract/api.js';
import { palette } from '../../src/core/palette.js';
import { hex, rgbaAt, type Frame } from './frame.js';

/** Everything that can change a pixel between machines. A golden compares strictly only where all of it matches. */
export interface RenderEnv {
  playwright: string;
  browser: string;
  platform: string;
  arch: string;
  /** UNMASKED_RENDERER_WEBGL: proves the frame came from SwiftShader. */
  webgl: string;
}

/** What a twin records besides the pixels: renderer.info figures and the environment. */
export interface TwinRecord { stats: Pick<RenderStats, 'drawCalls' | 'triangles'>; env: RenderEnv }

/** Off-palette colours listed one per line before the rest are summed (the depth fade makes some). */
const MAX_OFF_PALETTE_LINES = 32;

/** Every palette colour in declaration order, with all the entry paths that use it. */
function paletteNames(): Map<string, string[]> {
  const out = new Map<string, string[]>();
  const walk = (v: unknown, at: string): void => {
    if (typeof v === 'string') out.set(v, [...(out.get(v) ?? []), at]);
    else if (Array.isArray(v)) v.forEach((x, i) => walk(x, `${at}[${i}]`));
    else if (typeof v === 'object' && v !== null) for (const [k, x] of Object.entries(v)) walk(x, at ? `${at}.${k}` : k);
  };
  walk(palette, '');
  return out;
}
const NAMES = paletteNames();

interface Tally { px: number; x0: number; y0: number; x1: number; y1: number }

/** Basis points as a percentage with two decimals, in integer maths so the text never depends on float formatting. */
export const share = (px: number, total: number) => {
  const bp = Math.floor((px * 10000) / total);
  return `${Math.floor(bp / 100)}.${String(bp % 100).padStart(2, '0')}%`;
};

/** One line of JSON, keys in codepoint order (the env object is flat). */
export const envJson = (env: RenderEnv) => JSON.stringify(env, Object.keys(env).sort(byCodepoint));

/**
 * Off-palette pixels, as problems: with the depth fade off there must be none (system-design §10),
 * because the fade is the only off-palette output. Membership is exact, against src/core/palette.ts.
 */
export function paletteProblems(f: Frame): string[] {
  let n = 0, first = -1;
  for (let p = 0; p < f.width * f.height; p++) {
    if (NAMES.has(hex(rgbaAt(f.rgba, p * 4)))) continue;
    if (first < 0) first = p;
    n++;
  }
  if (!n) return [];
  return [`${n} px off-palette with the depth fade off, first ${hex(rgbaAt(f.rgba, first * 4))} at ${first % f.width},${Math.floor(first / f.width)}`];
}

export function twinText(name: string, f: Frame, { stats, env }: TwinRecord): string {
  const { width: w, height: h, rgba } = f;
  const total = w * h;
  // Keyed by RGB: the target is opaque, and the hash catches any change to alpha.
  const byRgb = new Map<number, Tally>();
  for (let p = 0; p < total; p++) {
    const rgb = rgbaAt(rgba, p * 4) | 0xff;
    const x = p % w, y = (p - x) / w;
    const t = byRgb.get(rgb);
    if (!t) byRgb.set(rgb, { px: 1, x0: x, y0: y, x1: x, y1: y });
    else { t.px++; t.x0 = Math.min(t.x0, x); t.y0 = Math.min(t.y0, y); t.x1 = Math.max(t.x1, x); t.y1 = Math.max(t.y1, y); }
  }
  const tallies = new Map([...byRgb].map(([rgb, t]) => [hex(rgb), t]));
  const line = (key: string, t: Tally, names: string) =>
    `${String(t.px).padStart(6)}  ${share(t.px, total).padStart(7)}  ${key}  ${`${t.x0},${t.y0}-${t.x1},${t.y1}`.padEnd(15)}  ${names}`.trimEnd();
  const onPalette = [...NAMES].flatMap(([key, names]) => { const t = tallies.get(key); return t ? [line(key, t, names.join(', '))] : []; });
  const off = [...tallies.keys()].filter((key) => !NAMES.has(key)).sort(byCodepoint);
  const offPx = (keys: string[]) => keys.reduce((a, key) => a + tallies.get(key)!.px, 0);
  const offLines = off.slice(0, MAX_OFF_PALETTE_LINES).map((key) => line(key, tallies.get(key)!, '(off-palette)'));
  const rest = off.slice(MAX_OFF_PALETTE_LINES);
  if (rest.length) offLines.push(`… and ${rest.length} more off-palette colours, ${offPx(rest)} px`);
  return [
    `# Text twin of ${name}.png, generated by test/render/twin.ts. Don't edit: regenerate with UPDATE_GOLDEN=1.`,
    `name     ${name}`,
    `env      ${envJson(env)}`,
    `size     ${w}x${h} (${total} px)`,
    `rgba     sha256 ${createHash('sha256').update(rgba).digest('hex')}`,
    `stats    drawCalls ${stats.drawCalls}, triangles ${stats.triangles}`,
    `colours  ${tallies.size} (${onPalette.length} palette, ${off.length} off-palette: ${offPx(off)} px)`,
    '',
    `    px    share  colour   bbox x0,y0-x1,y1  palette entries`,
    ...onPalette,
    ...offLines,
    '',
  ].join('\n');
}

/** The parts of a twin not derived from its image: the stats and env lines. */
export function twinRecord(text: string): TwinRecord {
  const stats = /^stats {4}drawCalls (\d+), triangles (\d+)$/m.exec(text);
  const env = /^env {6}(\{.*\})$/m.exec(text);
  if (!stats || !env) throw new Error(`twin has no ${stats ? 'env' : 'stats'} line`);
  return { stats: { drawCalls: Number(stats[1]), triangles: Number(stats[2]) }, env: JSON.parse(env[1]!) as RenderEnv };
}
