/** Rows per line: 5 for caps and digits, plus a descender row. */
export const FONT_HEIGHT = 6;
/** Ink-free columns between glyphs. */
export const FONT_SPACING = 1;
/** Drawn for any character the font lacks, so a label never silently loses a character. */
export const MISSING = '?';

/**
 * The glyph for a character. One the font lacks falls back to its base letter when it has one
 * (é → e, Å → A: decomposed, accents dropped), so names stay readable and distinct; anything else
 * is drawn as MISSING, never dropped. The DOM summary keeps the exact text for screen readers.
 */
export function glyph(ch: string): readonly string[] {
  return GLYPHS[ch] ?? GLYPHS[ch.normalize('NFD').replace(/\p{M}/gu, '')] ?? GLYPHS[MISSING]!;
}

export const hasGlyph = (ch: string): boolean => ch in GLYPHS;

/** A text mask: `bits[y * w + x]` is 1 where there is ink. */
export interface TextMask { w: number; h: number; bits: Uint8Array }

/** Width of a line in font pixels, without rasterising it. */
export const textWidth = (text: string): number =>
  Math.max(0, [...text].reduce((sum, ch) => sum + glyph(ch)[0]!.length + FONT_SPACING, -FONT_SPACING));

/** Rasterises one line of text in font pixels. */
export function rasterText(text: string): TextMask {
  const glyphs = [...text].map(glyph);
  const w = textWidth(text);
  const h = FONT_HEIGHT;
  const bits = new Uint8Array(w * h);
  let cx = 0;
  for (const g of glyphs) {
    g.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') bits[y * w + cx + x] = 1;
    });
    cx += g[0]!.length + FONT_SPACING;
  }
  return { w, h, bits };
}
